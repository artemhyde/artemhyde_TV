#!/usr/bin/env bash
# find-tv.sh: найти ТВ в сети через mDNS (без перебора адресов), подключиться по adb и проверить, что он отвечает (get-state).
# Запуск: bash tools/find-tv.sh                         показать ТВ, которые объявили беспроводную отладку (adb mdns)
#         bash tools/find-tv.sh 192.168.0.10:41234      подключиться (адрес и порт с ГЛАВНОГО экрана «Беспроводная отладка») и проверить связь
#         bash tools/find-tv.sh 192.168.0.10            порт ищется через mDNS; не нашёлся: пробуется 5555 (подходит только если отладка уже включена по 5555)
#         bash tools/find-tv.sh --pair 192.168.0.10:37123 123456   сопряжение по коду (адрес, порт и код из окна «Подключить устройство с помощью кода»)
# У беспроводной отладки порт случайный, и портов два: у главного экрана (для connect) и у окна сопряжения (для pair). Они разные.
# Итог: последняя строка TV=адрес, если ТВ отвечает. Код выхода: 0 готов, 2 нужно разрешить на экране ТВ, 3 не отвечает, 4 нужно сопряжение (--pair).
# Адрес не записывается никуда: мастер кладёт его только в config/settings.local.json и backup/ (они не попадают в git).
set -uo pipefail
source "$(dirname "$0")/lib.sh"
gt_find_adb || exit 1

if [ "${1:-}" = "--pair" ]; then
    [ $# -eq 3 ] || gt_die "Нужно: --pair адрес:порт_окна_сопряжения код_с_экрана"
    pout="$("$ADB" pair "$2" "$3" 2>&1 | tr -d '\r')"; prc=$?
    gt_say "$pout"
    if printf '%s' "$pout" | grep -qiE 'unknown command|usage:'; then
        gt_say "Этот adb не умеет pair: обновите platform-tools (нужна версия 30 или новее)."
        exit 1
    fi
    if printf '%s' "$pout" | grep -qi 'Successfully paired'; then
        gt_say "Сопряжение есть. Теперь подключитесь: bash tools/find-tv.sh <адрес:порт с ГЛАВНОГО экрана «Беспроводная отладка»> (порт другой, не из окна сопряжения)."
        exit 0
    fi
    gt_say "Не вышло. Проверьте код (он живёт недолго: окно «Подключить устройство с помощью кода» закрылось или код сменился) и адрес:порт именно этого окна."
    exit 1
fi

addr="${1:-}"
if [ -z "$addr" ]; then
    gt_say "ТВ, объявившие беспроводную отладку в этой сети (adb mdns services):"
    list="$("$ADB" mdns services 2>&1 | tr -d '\r')"
    if printf '%s\n' "$list" | grep -qE '_adb'; then
        printf '%s\n' "$list" | grep -E '_adb' | sed 's/^/  /'
        gt_say "Для подключения: bash tools/find-tv.sh <адрес:порт> из строки _adb-tls-connect."
        gt_say "Если сопряжения ещё не было: Настройки, Система, Для разработчиков, Беспроводная отладка, «Сопряжение по коду», затем --pair."
    else
        gt_say "  ничего не найдено."
        gt_say "Проверьте: ПК и ТВ в одной сети, на ТВ включена «Беспроводная отладка» (при включённой отладке по USB тоже нужен Wi-Fi)."
        gt_say "Или введите адрес с экрана ТВ (Настройки, Сеть) вручную: bash tools/find-tv.sh <адрес>"
    fi
    exit 3
fi

case "$addr" in
    *:*) ;;
    *)
        # Порт беспроводной отладки случайный: ищем его по mDNS (строка _adb-tls-connect с этим адресом), 5555 только запасной вариант
        found="$("$ADB" mdns services 2>/dev/null | tr -d '\r' | grep '_adb-tls-connect' | grep -F "$addr:" | awk '{print $NF}' | head -1)"
        if [ -n "$found" ]; then
            gt_say "Порт найден через mDNS: $found"
            addr="$found"
        else
            gt_say "Порт не указан и через mDNS не найден, пробую $addr:5555. У беспроводной отладки порт случайный: адрес и порт написаны на ГЛАВНОМ экране «Беспроводная отладка» (не в окне сопряжения)."
            addr="$addr:5555"
        fi ;;
esac
out="$("$ADB" connect "$addr" 2>&1 | tr -d '\r')"
gt_say "adb connect: $out"
if printf '%s' "$out" | grep -qi 'failed to authenticate'; then
    gt_say "Нужно сопряжение: ТВ не знает этот компьютер. На ТВ: Настройки, Система, Для разработчиков, Беспроводная отладка, «Подключить устройство с помощью кода»."
    gt_say "В этом окне свои адрес:порт и шестизначный код. Затем: bash tools/find-tv.sh --pair <адрес:порт окна сопряжения> <код>, потом снова connect с адресом:портом главного экрана."
    exit 4
fi
TV="$addr"; export TV
state="$(tv_state)"
case "$state" in
    device)
        gt_say "Связь есть (get-state: device)."
        echo "TV=$addr"
        exit 0 ;;
    unauthorized)
        gt_say "ТВ не доверяет этому ПК: на экране ТВ появилось окно «Разрешить отладку по USB/Wi-Fi?», нажмите «Разрешить» (по желанию с галочкой «всегда») и запустите скрипт ещё раз."
        exit 2 ;;
    *)
        gt_say "ТВ не отвечает (get-state: $state). Проверьте: адрес и порт с ГЛАВНОГО экрана «Беспроводная отладка» (порт случайный и после перезагрузки или смены Wi-Fi меняется), включена ли отладка, не ушёл ли ТВ в сон."
        if printf '%s' "$out" | grep -qiE 'refused|cannot connect|unable to connect|timed out|no route'; then
            gt_say "Если ТВ ни разу не сопрягали с этим компьютером, сначала сопряжение: bash tools/find-tv.sh --pair <адрес:порт окна сопряжения> <код>."
        fi
        exit 3 ;;
esac
